"""Emit explicit Rust operations and Clap parsers for selected contracts."""
import json
from .naming import pascal, snake, kebab


def qualify_cli_type(value):
    import re
    builtins = {"String", "Option", "Vec", "PathBuf", "BTreeMap", "Value"}
    return re.sub(r"(?<![:A-Za-z0-9_])([A-Z][A-Za-z0-9_]*)(?![:A-Za-z0-9_])", lambda match: match.group(1) if match.group(1) in builtins else "models::" + match.group(1), value)


def body_schema(contract, operation):
    if not operation.body:
        return None
    content = operation.body.get("content", {})
    media = content.get("application/json") or content.get("text/json")
    if not media:
        raise ValueError(f"non-JSON body requires a manual typed module: {operation.id}")
    return contract.resolve(media.get("schema", {}))


def response_type(contract, operation, models):
    if operation.response is None:
        return "()"
    schema = dict(operation.response)
    if "$ref" not in schema and schema.get("type") == "object":
        schema["x-generated-name"] = pascal(operation.cli.split()[-1]) + "Response"
    return models.reference(schema)


def method_name(operation):
    return snake(operation.cli.split()[-1])


def operation_const(operation):
    return pascal(operation.cli.split()[1]) + pascal(operation.cli.split()[-1])


def rust_value(value):
    return json.dumps(value)


def emit_models(contract, operations, models):
    for operation in operations:
        for parameter in operation.parameters:
            parameter_schema = dict(parameter.schema)
            if parameter_schema.get("enum"):
                parameter_schema["x-generated-name"] = pascal(method_name(operation)) + pascal(parameter.name)
                parameter_schema["x-request-enum"] = True
            models.reference(parameter_schema)
        schema = body_schema(contract, operation)
        if schema:
            schema = dict(schema)
            schema["x-request-model"] = True
            if "$ref" not in schema and schema.get("type") == "object":
                schema["x-generated-name"] = pascal(operation.cli.split()[-1]) + "Request"
            models.reference(schema)
        response_type(contract, operation, models)
    return models.render()


def emit_operations(contract, operations, models):
    chunks = ["// @generated by scripts/gen_typed_api.py. Do not edit.\n", "pub use super::models;",
"use super::models::*;", "use crate::rbx::client::{AsyncClient, Error, Operation as TransportOperation, Request, Server};",
"pub use self::params::*;", "use serde::de::DeserializeOwned;", ""]
    chunks.append("#[derive(Debug, Clone)]\npub struct CloudClient { transport: AsyncClient }\n")
    chunks.append("impl CloudClient {\n    pub fn new(transport: AsyncClient) -> Self { Self { transport } }\n")
    for operation in operations:
        name = method_name(operation)
        for parameter in operation.parameters:
            if parameter.schema.get("enum"):
                schema = dict(parameter.schema)
                schema["x-generated-name"] = pascal(name) + pascal(parameter.name)
                models.reference(schema)
        params = pascal(name) + "Params"
        response = response_type(contract, operation, models)
        server = {"https://apis.roblox.com": "Apis", "https://itemconfiguration.roblox.com": "ItemConfiguration", "https://thumbnails.roblox.com": "Thumbnails"}[operation.server]
        constructor = operation.method.lower()
        if operation.id == "GET /cloud/v2/universes/{universe_id}/memory-store/queues/{queue_id}/items:read":
            constructor = "get_once"
        if constructor not in ["get", "get_once", "post", "put", "patch", "delete"]:
            raise ValueError(operation.method)
        chunks.append(f"    pub async fn {name}(&self, params: {params}) -> Result<{response}, Error> {{\n")
        has_arrays = any(p.schema.get("type") == "array" and p.location == "query" for p in operation.parameters)
        binding = "mut request" if has_arrays else "request"
        chunks.append(f'        let {binding} = Request::new(TransportOperation::{constructor}(Server::{server}, {rust_value(operation.path)}))')
        array_queries = []
        for parameter in operation.parameters:
            field = snake(parameter.name)
            if parameter.location == "path":
                chunks.append(f'            .path_param({rust_value(parameter.name)}, params.{field})')
            elif parameter.location == "query":
                if parameter.schema.get("type") == "array":
                    array_queries.append((parameter.name, field, parameter.required))
                elif parameter.required:
                    chunks.append(f'            .query({rust_value(parameter.name)}, params.{field})')
                else:
                    chunks.append(f'            .query_opt({rust_value(parameter.name)}, params.{field})')
            elif parameter.location == "header":
                chunks.append(f'            .header({rust_value(parameter.name)}, params.{field})')
        body = body_schema(contract, operation)
        if body:
            chunks.append("            .json(&params.body)?")
        chunks.append(";\n")
        for wire, field, required in array_queries:
            if required:
                chunks.append(f"        for value in params.{field} {{ request = request.query({rust_value(wire)}, value); }}\n")
            else:
                chunks.append(f"        if let Some(values) = params.{field} {{ for value in values {{ request = request.query({rust_value(wire)}, value); }} }}\n")
        chunks.append("        let value = self.transport.execute(request).await?;\n")
        if response == "()":
            chunks.append("        let _ = value;\n        Ok(())\n")
        else:
            chunks.append(f'        decode::<{response}>({rust_value(operation.id)}, value)\n')
        chunks.append("    }\n")
    chunks.append("}\n")
    chunks.append('fn decode<T: DeserializeOwned>(operation: &str, value: serde_json::Value) -> Result<T, Error> {\n    serde_json::from_value(value).map_err(|error| Error::InvalidResponse { operation: operation.into(), status: 200, reason: error.to_string() })\n}\n')
    for operation in operations:
        name = method_name(operation)
        params = pascal(name) + "Params"
        chunks.append("#[derive(Debug, Clone)]\n")
        chunks.append(f"pub struct {params} {{\n")
        for parameter in operation.parameters:
            field = snake(parameter.name)
            parameter_schema = dict(parameter.schema)
            if parameter_schema.get("enum"):
                parameter_schema["x-generated-name"] = pascal(name) + pascal(parameter.name)
                parameter_schema["x-request-enum"] = True
            typ = qualify_cli_type(models.reference(parameter_schema))
            if parameter.location == "query" and not parameter.required:
                typ = f"Option<{typ}>"
            chunks.append(f"    pub {field}: {typ},\n")
        if body_schema(contract, operation):
            schema = dict(body_schema(contract, operation))
            schema["x-request-model"] = True
            if "$ref" not in schema:
                schema = dict(schema)
                schema["x-generated-name"] = pascal(operation.cli.split()[-1]) + "Request"
            chunks.append(f"    pub body: {models.reference(schema)},\n")
        chunks.append("}\n")
    return "".join(chunks).replace("pub use self::params::*;", "")


def emit_cli(contract, operations, models):
    groups = {}
    for operation in operations:
        _, group, command = operation.cli.split(" ", 2)
        groups.setdefault(group, []).append((command, operation))
    chunks = ["// @generated by scripts/gen_typed_api.py. Do not edit.\n", "use clap::{Args, Subcommand};\nuse rbxcloud::rbx::{client::{AsyncClient, ClientPolicy}, generated::CloudClient, credentials::Credentials};\nuse rbxcloud::rbx::generated::models;\n\n"]
    for group, entries in sorted(groups.items()):
        struct = pascal(group)
        enum = struct + "Command"
        chunks.append("#[derive(Debug, Args)]\n")
        chunks.append(f"pub struct {struct} {{\n    #[command(subcommand)]\n    command: {enum},\n}}\n")
        chunks.append("#[derive(Debug, Subcommand)]\n")
        chunks.append(f"enum {enum} {{\n")
        for command, operation in entries:
            variant = pascal(command)
            summary = " ".join(operation.summary.splitlines()).replace("*/", "* /")
            chunks.append(f"    /// {summary}\n    {variant} {{\n")
            model_types = {}
            for parameter in operation.parameters:
                schema = dict(parameter.schema)
                if schema.get("enum"):
                    schema["x-generated-name"] = pascal(method_name(operation)) + pascal(parameter.name)
                    schema["x-request-enum"] = True
                model_types[snake(parameter.name)] = qualify_cli_type(models.reference(schema))
            for parameter in operation.parameters:
                field = snake(parameter.name)
                typ = model_types[field]
                required = parameter.required or parameter.location == "path"
                if not required:
                    typ = f"Option<{typ}>"
                chunks.append(f"        #[arg(long)]\n        {field}: {typ},\n")
            schema = body_schema(contract, operation)
            if schema:
                properties = {name: value for name, value in schema.get("properties", {}).items() if not value.get("readOnly")}
                required_body = set(schema.get("required", []))
                for wire, original in properties.items():
                    field = "body_" + snake(wire)
                    schema_copy = dict(original)
                    schema_copy["x-generated-name"] = pascal(method_name(operation)) + "Request" + pascal(wire)
                    typ = qualify_cli_type(models.reference(schema_copy))
                    optional = wire not in required_body
                    is_json = "serde_json::Value" in typ or "BTreeMap<String, serde_json::Value>" in typ
                    if is_json or typ.startswith("models::GoogleProtobufValue"):
                        typ = "Option<String>" if optional else "String"
                        attribute = "#[arg(long, allow_hyphen_values = true)]"
                    else:
                        if optional:
                            typ = f"Option<{typ}>"
                        bare_type = typ.replace("Option<", "").rstrip(">")
                        attribute = "#[arg(long, allow_negative_numbers = true)]" if bare_type in ["i32", "i64", "u32", "u64", "f32", "f64"] else "#[arg(long)]"
                    chunks.append(f"        {attribute}\n        {field}: {typ},\n")
            chunks.append("    },\n")
        chunks.append("}\n")
        chunks.append(f"impl {struct} {{\n    pub async fn run(self) -> anyhow::Result<Option<String>> {{\n")
        chunks.append("        let credentials = Credentials::from_process()?;\n        let transport = AsyncClient::new(credentials, ClientPolicy::default()).await?;\n        let client = CloudClient::new(transport);\n        match self.command {\n")
        for command, operation in entries:
            variant = pascal(command)
            fields = [snake(p.name) for p in operation.parameters]
            schema = body_schema(contract, operation)
            body_fields = []
            if schema:
                body_fields = ["body_" + snake(name) for name, value in schema.get("properties", {}).items() if not value.get("readOnly")]
            pattern = fields + body_fields
            chunks.append(f"            {enum}::{variant} {{ {', '.join(pattern)} }} => {{\n")
            chunks.append(f"                let result = client.{method_name(operation)}(rbxcloud::rbx::generated::storage::{pascal(method_name(operation))}Params {{\n")
            for parameter in operation.parameters:
                field = snake(parameter.name)
                value = field
                if parameter.location == "query" and parameter.required:
                    value = field
                chunks.append(f"                    {field}: {value},\n")
            if schema:
                body_type = pascal(method_name(operation)) + "Request" if "$ref" not in schema else pascal(schema["$ref"].split("/")[-1]) + "Input"
                chunks.append(f"                    body: rbxcloud::rbx::generated::models::{body_type} {{\n")
                required = set(schema.get("required", []))
                for wire, original_body in schema.get("properties", {}).items():
                    if original_body.get("readOnly"):
                        continue
                    cli_name = "body_" + snake(wire)
                    field = snake(wire)
                    original = schema.get("properties", {})[wire]
                    is_json = original.get("type") == "object" and not original.get("properties") or not original.get("type") or "$ref" in original and original["$ref"].endswith("GoogleProtobufValue")
                    if is_json:
                        value = f"{cli_name}.as_deref().map(serde_json::from_str).transpose()?" if wire not in required else f"serde_json::from_str(&{cli_name})?"
                    else:
                        value = cli_name
                    model_optional = wire not in required
                    if not model_optional and original.get("nullable"):
                        value = f"Some({value})"
                    chunks.append(f"                        {field}: {value},\n")
                chunks.append("                    },\n")
            chunks.append("                }).await?;\n")
            chunks.append("                if serde_json::to_value(&result)?.is_null() { Ok(None) } else { Ok(Some(serde_json::to_string_pretty(&result)?)) }\n")
            chunks.append("            }\n")
        chunks.append("        }\n    }\n}\n")
    return "".join(chunks), groups
